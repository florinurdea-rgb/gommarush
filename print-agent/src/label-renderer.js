import PDFDocument from "pdfkit";
import bwipjs from "bwip-js";
import QRCode from "qrcode";

/**
 * Thermal label renderer.
 *
 * This is an INDUSTRIAL label, not a UI. Every design decision below serves one
 * of two goals: how fast a human recognises the right rack, and how reliably a
 * handheld scanner reads the barcode.
 *
 * Layout (default 100 × 70 mm, configurable):
 *
 *   ┌──────────────────────────────────────┐
 *   │  GR-001            ┌──────────────┐  │
 *   │  ROSSI GOMME       │              │  │
 *   │  MICHELIN          │      A       │  │   <- stand letter, dominant
 *   │  225/55 R18 98V    │              │  │
 *   │                    └──────────────┘  │
 *   │  ││││││││││││││││││││││││    ┌────┐  │   <- Code128, full width
 *   │  GRU9F3A…                    │ QR │  │
 *   └──────────────────────────────────────┘
 *
 * Pure black on white: thermal printers have no greyscale worth relying on, and
 * anti-aliased edges are what make a barcode fail to scan.
 */

const MM_TO_PT = 72 / 25.4;

function mm(value) {
  return value * MM_TO_PT;
}

/** Code128 as a PNG buffer. Rendered at high density for a crisp thermal print. */
async function renderCode128(text) {
  return bwipjs.toBuffer({
    bcid: "code128",
    text,
    // No human-readable text from bwip — we draw the token ourselves in a font
    // that matches the rest of the label.
    includetext: false,
    scale: 4,
    height: 14,
    paddingwidth: 0,
    paddingheight: 0,
    backgroundcolor: "FFFFFF",
  });
}

async function renderQr(text) {
  return QRCode.toBuffer(text, {
    errorCorrectionLevel: "M",
    margin: 0,
    scale: 8,
    color: { dark: "#000000", light: "#FFFFFF" },
  });
}

function truncate(value, max) {
  const text = String(value ?? "").trim();
  if (text.length <= max) return text;
  return `${text.slice(0, max - 1)}…`;
}

/** "GR-001" from the numeric order_number the database owns. */
function formatOrderNumber(orderNumber) {
  if (orderNumber === null || orderNumber === undefined || orderNumber === "") return "";
  const numeric = Number(orderNumber);
  if (!Number.isFinite(numeric)) return String(orderNumber);
  return `GR-${String(Math.trunc(numeric)).padStart(3, "0")}`;
}

/**
 * Renders one label to a PDF buffer.
 *
 * `labelData` is exactly the JSON stored on the print job. The printer does not
 * invent identifiers: the barcode and QR both carry the unit token generated by
 * the GoRush system.
 */
export async function renderLabelPdf(labelData, options = {}) {
  const widthMm = options.widthMm ?? 100;
  const heightMm = options.heightMm ?? 70;
  const marginMm = options.marginMm ?? 4;

  const unitToken = String(labelData.unit_token ?? "").trim();
  if (!unitToken) throw new Error("label_data.unit_token is required");

  const [barcodePng, qrPng] = await Promise.all([
    renderCode128(unitToken),
    // The QR carries a URL so a phone camera does something useful with it,
    // while the Code128 carries the bare token for the handheld scanner.
    renderQr(options.qrPayload ?? unitToken),
  ]);

  const pageWidth = mm(widthMm);
  const pageHeight = mm(heightMm);
  const margin = mm(marginMm);
  const contentWidth = pageWidth - margin * 2;

  const document = new PDFDocument({ size: [pageWidth, pageHeight], margin: 0 });
  const chunks = [];
  document.on("data", (chunk) => chunks.push(chunk));
  const done = new Promise((resolve) => document.on("end", () => resolve(Buffer.concat(chunks))));

  document.rect(0, 0, pageWidth, pageHeight).fill("#FFFFFF");
  document.fillColor("#000000");

  // ---- Stand letter: the dominant element, boxed on the right -------------
  const standBox = Math.min(mm(30), pageHeight * 0.42);
  const standX = pageWidth - margin - standBox;
  const standY = margin;

  document.lineWidth(2).rect(standX, standY, standBox, standBox).stroke("#000000");

  const standCode = String(labelData.stand_code ?? "").trim();
  if (standCode) {
    document
      .font("Helvetica-Bold")
      .fontSize(standBox * 0.72)
      .text(standCode, standX, standY + standBox * 0.13, {
        width: standBox,
        align: "center",
      });
  } else {
    // Never leave it blank: an unassigned stand must be visibly wrong on the
    // physical label so someone resolves it.
    document
      .font("Helvetica-Bold")
      .fontSize(standBox * 0.3)
      .text("FĂRĂ\nSTATIV", standX, standY + standBox * 0.26, {
        width: standBox,
        align: "center",
      });
  }

  document
    .font("Helvetica")
    .fontSize(6)
    .text("STATIV", standX, standY + standBox + 2, { width: standBox, align: "center" });

  // ---- Order / customer / product, left column ---------------------------
  const textWidth = contentWidth - standBox - mm(3);
  let cursorY = margin;

  document
    .font("Helvetica-Bold")
    .fontSize(15)
    .text(formatOrderNumber(labelData.order_number), margin, cursorY, { width: textWidth });
  cursorY += 18;

  document
    .font("Helvetica-Bold")
    .fontSize(12)
    .text(truncate(labelData.customer, 28).toUpperCase(), margin, cursorY, { width: textWidth });
  cursorY += 16;

  if (labelData.brand) {
    document
      .font("Helvetica-Bold")
      .fontSize(13)
      .text(truncate(labelData.brand, 20).toUpperCase(), margin, cursorY, { width: textWidth });
    cursorY += 15;
  }

  const sizeLine = [labelData.size, labelData.load_speed].filter(Boolean).join(" ").trim();
  if (sizeLine) {
    document
      .font("Helvetica-Bold")
      .fontSize(13)
      .text(truncate(sizeLine, 22), margin, cursorY, { width: textWidth });
    cursorY += 15;
  } else if (labelData.product) {
    document
      .font("Helvetica")
      .fontSize(9)
      .text(truncate(labelData.product, 44), margin, cursorY, { width: textWidth });
    cursorY += 12;
  }

  if (labelData.unit_index && labelData.unit_total) {
    document
      .font("Helvetica")
      .fontSize(9)
      .text(`Obiect ${labelData.unit_index} / ${labelData.unit_total}`, margin, cursorY, {
        width: textWidth,
      });
    cursorY += 11;
  }

  // Supplier + delivery address: only present on labels queued from the
  // "Pregătește comanda" flow (src/lib/server/prepare-order.ts in the web
  // app) — a deliberate exception to keeping addresses off labels in
  // general, made explicitly by the user for that flow. Absent on every
  // other label (e.g. the receiving-time one), so these stay optional.
  if (labelData.supplier) {
    document
      .font("Helvetica")
      .fontSize(8)
      .text(truncate(labelData.supplier, 34), margin, cursorY, { width: textWidth });
    cursorY += 10;
  }

  if (labelData.delivery_address) {
    document
      .font("Helvetica")
      .fontSize(8)
      .text(truncate(labelData.delivery_address, 46), margin, cursorY, { width: textWidth });
    cursorY += 10;
  }

  // ---- Machine-readable block along the bottom ---------------------------
  const qrSize = mm(18);
  const barcodeHeight = mm(13);
  const blockBottom = pageHeight - margin;

  document.image(qrPng, pageWidth - margin - qrSize, blockBottom - qrSize, {
    width: qrSize,
    height: qrSize,
  });

  const barcodeWidth = contentWidth - qrSize - mm(3);
  const barcodeY = blockBottom - qrSize;

  document.image(barcodePng, margin, barcodeY, {
    width: barcodeWidth,
    height: barcodeHeight,
  });

  // The token in text form, so a damaged barcode can still be keyed in.
  document
    .font("Courier-Bold")
    .fontSize(8)
    .text(unitToken, margin, barcodeY + barcodeHeight + 2, {
      width: barcodeWidth,
      align: "center",
    });

  document.end();
  return done;
}
